def mean(data):

    total = 0

    for value in data:
        total = total + value

    return total / len(data)
def variance(data):

    avg = mean(data)

    total = 0

    for value in data:
        total = total + (value - avg) ** 2

    return total / len(data)

def standard_deviation(data):
    return variance(data) ** 0.5
